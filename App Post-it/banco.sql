-- Execute uma única vez no SQL Editor do Supabase.
create table if not exists public.postits (
  id bigint generated by default as identity primary key,
  text text not null default '' check (char_length(text) <= 2000),
  color text not null default '#ffe66d' check (color ~ '^#[0-9a-fA-F]{6}$'),
  created_at timestamptz not null default now()
);

alter table public.postits enable row level security;
grant usage on schema public to anon;
grant select, insert, update, delete on public.postits to anon;
grant usage, select on sequence public.postits_id_seq to anon;

